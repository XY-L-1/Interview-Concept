import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const sourceDirectory = new URL(
  "../../learning/java-spring-interview-guide/",
  import.meta.url,
);
const outputFile = new URL(
  "../src/modules/content/java-guide-source.ts",
  import.meta.url,
);

const modules = [
  ["01-java-language.md", "java-language"],
  ["02-collections-generics-streams.md", "java-collections-generics-streams"],
  ["03-jvm.md", "java-jvm"],
  ["04-concurrency.md", "java-concurrency"],
  ["05-spring-core.md", "spring-core"],
  ["06-spring-boot-web.md", "spring-boot-web"],
  ["07-data-transactions-cache.md", "spring-data-transactions-cache"],
  ["08-production.md", "spring-production"],
];

const labels = [
  ["结论", "Conclusion"],
  ["展开", "Deep dive"],
  ["追问", "Follow-up"],
  ["易错点", "Common pitfall"],
];
const difficulties = {
  基础: "beginner",
  中级: "intermediate",
  高级: "advanced",
};

function parseModule(sourceFile, slug, moduleIndex) {
  const bytes = readFileSync(new URL(sourceFile, sourceDirectory));
  const lines = bytes.toString("utf8").split(/\r?\n/);
  const questions = [];
  let current;

  for (const [index, line] of lines.entries()) {
    if (index < 4 || !line.trim()) continue;

    const heading = line.match(/^## (\d{3})\. (.+)（(基础|中级|高级)）$/u);
    if (heading) {
      current = {
        questionNumber: heading[1],
        sourceLine: index + 1,
        difficulty: difficulties[heading[3]],
        prompt: { zhHans: `${heading[2]}（${heading[3]}）`, en: "" },
        blocks: labels.map(([labelZh, labelEn]) => ({
          labelZh,
          labelEn,
          zh: "",
          en: "",
        })),
      };
      questions.push(current);
      continue;
    }

    const paragraph = line.match(/^\*\*([^：:]+)[：:]\*\* (.*)$/u);
    if (!current || !paragraph) {
      throw new Error(`Unrecognized source at ${sourceFile}:${index + 1}`);
    }

    const [, label, text] = paragraph;
    if (label === "English question") {
      if (current.prompt.en) throw new Error(`Duplicate English question: ${sourceFile}:${index + 1}`);
      current.prompt.en = text;
      continue;
    }

    const block = current.blocks.find(
      (candidate) => candidate.labelZh === label || candidate.labelEn === label,
    );
    if (!block) throw new Error(`Unknown label: ${sourceFile}:${index + 1}`);
    const language = block.labelZh === label ? "zh" : "en";
    if (block[language]) throw new Error(`Duplicate block: ${sourceFile}:${index + 1}`);
    block[language] = text;
  }

  if (questions.length !== 20) throw new Error(`Expected 20 questions in ${sourceFile}`);
  questions.forEach((question, questionIndex) => {
    const expected = String(moduleIndex * 20 + questionIndex + 1).padStart(3, "0");
    if (question.questionNumber !== expected || !question.prompt.en) {
      throw new Error(`Missing or unordered question ${expected} in ${sourceFile}`);
    }
    if (question.blocks.some((block) => !block.zh || !block.en)) {
      throw new Error(`Incomplete bilingual blocks in ${sourceFile}, question ${expected}`);
    }
  });

  return {
    slug,
    sourceFile,
    sourceSha256: createHash("sha256").update(bytes).digest("hex"),
    title: {
      zhHans: lines[0].replace(/^# /u, ""),
      en: lines[2].replace(/^\*|\*$/gu, ""),
    },
    questions,
  };
}

export function generateJavaGuideSource() {
  const data = modules.map(([sourceFile, slug], index) =>
    parseModule(sourceFile, slug, index),
  );
  return [
    "// Generated by scripts/import-java-guide.mjs. Original bilingual text is preserved.",
    'import type { JavaGuideModule } from "./java-guide-source-model";',
    "",
    `export const javaGuideSource: readonly JavaGuideModule[] = ${JSON.stringify(data, null, 2)};`,
    "",
  ].join("\n");
}

if (
  process.argv[1] &&
  pathToFileURL(resolve(process.argv[1])).href === import.meta.url
) {
  const generated = generateJavaGuideSource();
  if (process.argv.includes("--check")) {
    if (readFileSync(outputFile, "utf8") !== generated) {
      throw new Error("Java guide snapshot differs. Run node scripts/import-java-guide.mjs.");
    }
    console.log("Java guide snapshot matches all 8 source modules and 160 questions.");
  } else {
    writeFileSync(outputFile, generated);
    console.log(`Imported 160 questions into ${fileURLToPath(outputFile)}.`);
  }
}
